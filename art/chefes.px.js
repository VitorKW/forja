for (const [nome, forma, [b, d, h, e], enfeite] of CHEFES) {
  // Cada chefe tem sua própria paleta: o pal() vale para os sprites seguintes.
  pal({ k: "#120d0b", b, d, h, e, m: "#2a0806", t: "#f4ecdc", x: "#e8dcc0" })
  const extras = (ENFEITES[enfeite] ?? []).map(([x, y, g]) => grid(x, y, g))
  sprite(nome, { w: 24, h: 24, mx: true, outline: "k" },
    grid(0, 0, FORMAS[forma].join("\n")),
    ...extras,
    glow("e", { r: 2, strength: 0.35 }))
}

