// Enfeites que diferenciam chefes que repetem a mesma forma.
const ENFEITES = {
  // Lodo de Escória: bolhas e pingos
  lodo: [[1, 2, "...h...h"], [0, 22, ".d...d"]],
  // Fole Uivante: chifres maiores
  fole: [[7, 0, "x\nxx\n.x"]],
  // Titã do Carvão: brasas acesas nas rachaduras
  tita: [[2, 13, "...e\n..ee\n...e"], [8, 2, "..h"]],
  // Dragão: asas atrás do corpo e chifres longos
  dragao: [[0, 6, "d\ndd\ndbd\ndbbd\ndbbbd\n.dbbbd\n..dbbb\n...ddd"], [6, 0, ".x\nxx"]],
  // Rainha: coroa sobre o elmo
  rainha: [[8, 0, "t.t.\ntttt"], [10, 0, "..t\n.tt"]],
  // Chefe do mês: coroa larga e brasas nos ombros
  coroa: [[7, 0, "t.t.t\nttttt"], [1, 9, ".ee\neee"]],
}

